import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const webDirectory = resolve(scriptDirectory, "..");
const projectDirectory = resolve(webDirectory, "..", "..");
const htmlPath = join(webDirectory, "dist", "index.html");
const headerPath = join(projectDirectory, "src", "control_panel_page.h");

function collectFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === "node_modules" || entry.name === "dist")
      continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory())
      files.push(...collectFiles(path));
    else if (entry.name !== ".DS_Store")
      files.push(path);
  }
  return files;
}

function sourceFingerprint() {
  const hash = createHash("sha256");
  for (const path of collectFiles(webDirectory).sort()) {
    hash.update(relative(webDirectory, path));
    hash.update("\0");
    hash.update(readFileSync(path));
    hash.update("\0");
  }
  return hash.digest("hex");
}

if (!existsSync(htmlPath))
  throw new Error(`Vite output is missing: ${htmlPath}`);

const html = readFileSync(htmlPath);
const compressed = gzipSync(html, { level: 9, mtime: 0 });
const bytesPerLine = 20;
const lines = [];
for (let offset = 0; offset < compressed.length; offset += bytesPerLine) {
  const bytes = [...compressed.subarray(offset, offset + bytesPerLine)]
    .map((value) => `0x${value.toString(16).padStart(2, "0")}`)
    .join(", ");
  lines.push(`    ${bytes},`);
}

const header = `#pragma once

#include <Arduino.h>

// Generated by web/control-panel/scripts/html-to-header.mjs.
// Web source SHA-256: ${sourceFingerprint()}
// Original HTML: ${html.length} bytes; gzip: ${compressed.length} bytes.
static const uint8_t kControlPanelPageGzip[] PROGMEM = {
${lines.join("\n")}
};

static constexpr size_t kControlPanelPageGzipLength =
    sizeof(kControlPanelPageGzip);
`;

if (!existsSync(headerPath) || readFileSync(headerPath, "utf8") !== header)
  writeFileSync(headerPath, header);

console.log(
  `Control panel: ${html.length} byte HTML -> ` +
  `${compressed.length} byte gzip header`,
);
